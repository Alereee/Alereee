import { expect, test } from '@playwright/test';

import { SITE_API_URL } from '../config';

// Server-rendered word pages over the public API (issue #330); the data is
// the fixture dictionary seeded in site.setup.ts
test.describe('word pages', () => {
  test('a headword renders its entries from the fixture data', async ({ page }) => {
    await page.goto('/en/word/run');

    await expect(page.getByRole('heading', { level: 1, name: 'run' })).toBeVisible();
    // one seeded entry: the verb, with its meaning and the synonym link
    await expect(page.getByRole('heading', { level: 2, name: 'verb' })).toBeVisible();
    await expect(page.getByText('to move fast').first()).toBeVisible();
    await expect(page.getByRole('link', { name: 'sprint' })).toHaveAttribute('href', /\/en\/word\/sprint$/);
    // the page names the API call it renders
    await expect(page.getByText('GET /api/v1/words/run')).toBeVisible();
    // one translation language at a time (issue #520): the fixture has Russian only, so it
    // shows by default, flagged, and there is nothing to pick from
    await expect(page.getByText('бежать').first()).toBeVisible();
    await expect(page.getByRole('img', { name: 'ru' }).first()).toBeVisible();
    await expect(page.getByRole('group', { name: 'Language' })).toHaveCount(0);
  });

  // issue #531: the note under a word page leads to the terms of the data it shows
  test('the terms of the data are a page of the site', async ({ page }) => {
    await page.goto('/en/dataset-terms');

    await expect(page.getByRole('heading', { level: 1, name: 'Terms of the dictionary data' })).toBeVisible();
    await expect(page.getByRole('link', { name: 'CC BY 4.0', exact: true })).toHaveAttribute(
      'href',
      'https://creativecommons.org/licenses/by/4.0/',
    );
    await expect(page.getByText('Generated by language models')).toBeVisible();
    // the project's own data is named by the link of its license: no notice to print in full
    await expect(page.getByTestId('license-text')).toHaveCount(0);

    // what the license asks of whoever takes the data further: the mark and the history are named
    const use = page.getByTestId('terms-of-use');
    await expect(use.getByRole('heading', { name: 'If you use this data' })).toBeVisible();
    await expect(use.getByRole('listitem')).toHaveCount(4);
    await expect(use).toContainText('carries modified: true');
    await expect(use).toContainText('GET /api/v1/words/{word}/history');
    // CC BY 4.0 is not share-alike and has no notice to keep in full
    await expect(use).not.toContainText('share-alike');
    await expect(use.getByRole('link', { name: 'The terms in detail' })).toHaveAttribute(
      'href',
      '/en/docs/data-license#using-data-that-was-changed-on-an-instance',
    );

    await page.goto('/ru/dataset-terms');
    await expect(page.getByRole('heading', { name: 'Если вы используете эти данные' })).toBeVisible();
  });

  // issue #531: the fixture words are made through the admin API — they are
  // the owner's, not what a source says, and the page tells the reader
  test('an entry made on the instance says that it was changed or added by its owner', async ({
    page,
    request,
  }) => {
    await page.goto('/en/word/run');
    await expect(page.getByTestId('entry-modified')).toHaveText('changed or added by the owner of this site');

    await page.goto('/ru/word/run');
    await expect(page.getByTestId('entry-modified')).toHaveText('изменено или добавлено владельцем сайта');

    const api = await request.get(`${SITE_API_URL}/v1/words/run`);
    expect((await api.json()).data[0]).toEqual(expect.objectContaining({ modified: true }));
  });

  // issue #531: not only that an entry was changed, but what was, and who sent the correction
  test('the page of an edited word says what was changed', async ({ page, request }) => {
    await page.goto('/en/word/sprint');

    const history = page.getByTestId('word-history');
    await expect(history.locator('summary')).toHaveText('What was changed on this site');
    await history.locator('summary').click();
    await expect(history.getByRole('link', { name: 'What this means if you use the data' })).toHaveAttribute(
      'href',
      '/en/dataset-terms',
    );
    const items = history.getByTestId('word-history-item');
    await expect(items).toHaveCount(2);

    // the latest first: the correction, then the word as it was added
    await expect(items.nth(0)).toContainText('Entry: changed');
    await expect(items.nth(0).getByTestId('word-history-author')).toHaveText(
      'a correction sent by Ada Lovelace',
    );
    await expect(items.nth(0)).toContainText('description');
    await expect(items.nth(0).locator('ins')).toHaveText('to run at full speed for a short distance');
    await expect(items.nth(0).locator('del')).toHaveText('—');
    await expect(items.nth(1)).toContainText('Entry: added');
    await expect(items.nth(1).locator('dl')).toHaveCount(0);

    await page.goto('/ru/word/sprint');
    await expect(page.getByTestId('word-history').locator('summary')).toHaveText('Что изменено на этом сайте');

    const api = await request.get(`${SITE_API_URL}/v1/words/sprint/history`);
    const { data, meta } = await api.json();
    expect(meta).toEqual({ word: 'sprint', count: 2, variants: [] });
    expect(data[0]).toEqual(
      expect.objectContaining({
        origin: 'suggestion',
        author: 'Ada Lovelace',
        entity: 'word',
        action: 'update',
      }),
    );
  });

  // "Polish" and "polish" are two words: two pages, each with its entries and its own history
  test('spellings that differ by case are pages of their own', async ({ page }) => {
    const upper = await page.goto('/en/word/Polish');
    expect(upper?.status()).toBe(200);
    await expect(page).toHaveURL(/\/en\/word\/Polish$/);
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Polish');
    await expect(page.getByRole('heading', { level: 2 })).toHaveText(['noun']);
    // the description of the entry; the history under it holds the same words, folded
    await expect(page.getByText('the language spoken in Poland').first()).toBeVisible();
    await expect(page.getByTestId('other-spellings').getByRole('link', { name: 'polish' })).toHaveAttribute(
      'href',
      '/en/word/polish',
    );

    await page.goto('/en/word/polish');
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('polish');
    await expect(page.getByRole('heading', { level: 2 })).toHaveText(['verb']);
    await expect(page.getByText('the language spoken in Poland')).toHaveCount(0);
    await expect(page.getByTestId('other-spellings').getByRole('link', { name: 'Polish' })).toBeVisible();

    // a spelling the dictionary does not hold as it is leads to the lower-case one
    await page.goto('/en/word/POLISH');
    await expect(page).toHaveURL(/\/en\/word\/polish$/);
    // …and where the dictionary holds one spelling, the case never mattered
    await page.goto('/en/word/Sprint');
    await expect(page).toHaveURL(/\/en\/word\/sprint$/);
    await expect(page.getByTestId('other-spellings')).toHaveCount(0);
  });

  // every part of speech has the block of its own edits, under the entry they were made in
  test('the edits of an entry are shown under that entry', async ({ page }) => {
    await page.goto('/en/word/Polish');
    const entry = page
      .locator('section')
      .filter({ has: page.getByRole('heading', { level: 2, name: 'noun' }) });
    const history = entry.getByTestId('word-history');
    await expect(history.locator('summary svg')).toHaveCount(1);
    await history.locator('summary').click();
    const items = history.getByTestId('word-history-item');
    await expect(items).toHaveCount(2);
    await expect(items.nth(0).locator('del')).toHaveText('the language of Poland');
    await expect(items.nth(0).locator('ins')).toHaveText('the language spoken in Poland');

    // "run" is a verb and a noun, each added on the instance: a block under each, none for the page as a whole
    await page.goto('/en/word/run');
    await expect(page.getByTestId('word-history')).toHaveCount(
      await page.getByRole('heading', { level: 2 }).count(),
    );
    for (const block of await page.getByTestId('word-history').all()) {
      await block.locator('summary').click();
      await expect(block.getByTestId('word-history-item')).toHaveCount(1);
    }
  });

  // issue #480: the Russian copy leads with the Russian translation — in the
  // title, the description and on the first screen
  test("a word page in a translated locale leads with that locale's translations", async ({ page }) => {
    await page.goto('/ru/word/run');

    await expect(page).toHaveTitle('run — перевод: бежать · Vocab Bloom Hub');
    await expect(page.locator('meta[name="description"]')).toHaveAttribute(
      'content',
      'Перевод слова run на русский: бежать. definition of to move fast',
    );
    await expect(page.getByText('Перевод: бежать')).toBeVisible();
    // …and the entry's own short translation is in the open
    await expect(page.getByText('бежать').nth(1)).toBeVisible();
    // the English copy has no such lead
    await page.goto('/en/word/run');
    await expect(page).toHaveTitle('run — meanings, forms, translations · Vocab Bloom Hub');
    await expect(page.getByText('Translation:')).toHaveCount(0);
  });

  test('the word index offers the search and the examples', async ({ page }) => {
    await page.goto('/en/word');

    const search = page.getByRole('search').first();
    await search.getByRole('searchbox').fill('run');
    await search.getByRole('button', { name: 'Search' }).click();
    await expect(page.getByRole('link', { name: 'run', exact: true }).first()).toBeVisible();
    // the term lands in the URL so the search can be shared (issue #399)
    await expect(page).toHaveURL(/\?q=run$/);
  });

  test('opening a ?q= link restores the search (issue #399)', async ({ page }) => {
    await page.goto('/en/word?q=sprint');

    await expect(page.getByRole('searchbox')).toHaveValue('sprint');
    await expect(page.getByRole('link', { name: 'sprint', exact: true }).first()).toBeVisible();
  });

  test('a missing headword answers 404', async ({ page }) => {
    const response = await page.goto('/en/word/no-such-headword');

    expect(response?.status()).toBe(404);
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Page not found');
  });

  test('/word/random redirects to a headword', async ({ request }) => {
    const response = await request.get('/en/word/random', { maxRedirects: 0 });

    expect(response.status()).toBe(307);
    // relative: behind a reverse proxy the server does not know its public origin
    expect(response.headers()['location']).toMatch(/^\/en\/word\/.+$/);
  });

  test('the edit mode of the report form files a form proposal (issue #327)', async ({ page }) => {
    await page.goto('/en/word/abandon');

    // one entry point: the report button, then the edit-the-entry mode
    await page.getByRole('button', { name: 'Report a mistake' }).click();
    const form = page.getByRole('form', { name: 'Report a mistake' });
    await form.getByRole('button', { name: 'Edit the entry' }).click();

    // the full word form opens prefilled; only the changed values are sent
    await form.getByLabel('Description').fill('to leave somebody or something behind for good');
    await form.getByRole('button', { name: 'Suggest the changes' }).click();

    await expect(page.getByText('Thank you — the proposal is in the moderation queue.')).toBeVisible();
  });

  test('a too-short text report shows a validation message instead of doing nothing (issue #351)', async ({
    page,
  }) => {
    await page.goto('/en/word/run');

    await page.getByRole('button', { name: 'Report a mistake' }).click();
    const form = page.getByRole('form', { name: 'Report a mistake' });
    await form.getByRole('textbox', { name: 'What is wrong' }).fill('too short');
    await form.getByRole('button', { name: 'Send the report' }).click();

    await expect(page.getByText('Please describe the mistake in at least 10 characters.')).toBeVisible();
  });

  test('the report form files a suggestion into the instance queue (issue #327)', async ({ page }) => {
    await page.goto('/en/word/run');

    await page.getByRole('button', { name: 'Report a mistake' }).click();
    const form = page.getByRole('form', { name: 'Report a mistake' });
    await form
      .getByRole('textbox', { name: 'What is wrong' })
      .fill('The definition of "to move fast" misses that it is on foot — e2e report.');
    await form.getByRole('button', { name: 'Send the report' }).click();

    await expect(page.getByText('Thank you — the report is in the moderation queue.')).toBeVisible();
  });

  // issue #531: a name is published with the correction, so it is taken with the sender's word only
  test('a sender is named only when they agree to it', async ({ page }) => {
    await page.goto('/en/word/run');

    await page.getByRole('button', { name: 'Report a mistake' }).click();
    const form = page.getByRole('form', { name: 'Report a mistake' });
    await form
      .getByRole('textbox', { name: 'What is wrong' })
      .fill('The example of "to move fast" has a typo — e2e report with a name.');
    // nobody is asked to agree to anything before they give a name
    await expect(form.getByRole('checkbox')).toHaveCount(0);
    await form.getByRole('textbox', { name: /Your name/ }).fill('Ada Lovelace');
    await form.getByRole('button', { name: 'Send the report' }).click();
    await expect(page.getByText('Tick the box to be named, or leave the name empty.')).toBeVisible();

    await form.getByRole('checkbox', { name: /Show this name next to the correction/ }).check();
    await form.getByRole('button', { name: 'Send the report' }).click();
    await expect(page.getByText('Thank you — the report is in the moderation queue.')).toBeVisible();
  });
});
