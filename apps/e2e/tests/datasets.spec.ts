import { expect, test } from '@playwright/test';

import { API_URL } from '../config';

// The datasets of the instance in the admin UI (issue #527). The browser
// suite runs on SQLite, a driver without schemas: the page shows the catalog
// and the instruction of every dataset, and nothing that would install,
// switch or delete one. What an installation does is the subject of the
// server suites on Postgres.
test.describe('datasets', () => {
  test('the managing page links the datasets page', async ({ page }) => {
    await page.goto('/en/managing');

    await page.getByRole('link', { name: 'Datasets' }).click();
    await expect(page).toHaveURL(/\/en\/managing\/datasets$/);
    await expect(page.getByRole('heading', { level: 2, name: 'Datasets' })).toBeVisible();
  });

  test('shows every dataset of the catalog with its license, the one of the project active', async ({
    page,
  }) => {
    await page.goto('/en/managing/datasets');

    await expect(page.getByTestId('datasets-unsupported')).toContainText('needs a Postgres database');
    // an installed dataset is read by the public API before it is activated (issue #528)
    await expect(page.getByTestId('datasets-public-note')).toContainText(
      'An installed dataset is public, active or not: GET /api/v1/words/{word}/datasets',
    );

    const own = page.getByTestId('dataset-default');
    await expect(own).toContainText('Vocab Bloom Hub English dataset');
    await expect(own).toContainText('active');
    await expect(own.getByRole('link', { name: /CC-BY-4\.0/ })).toHaveAttribute(
      'href',
      'https://creativecommons.org/licenses/by/4.0/',
    );
    await expect(own).toContainText('Generated by language models');
    await expect(own.getByRole('link', { name: 'Open the import page' })).toHaveAttribute(
      'href',
      '/en/managing/import-dictionary',
    );

    const wiktionary = page.getByTestId('dataset-wiktionary');
    await expect(wiktionary).toContainText('English Wiktionary');
    await expect(wiktionary).toContainText('not installed');
    await expect(wiktionary).toContainText('share-alike');
    await expect(wiktionary.getByRole('link', { name: /CC-BY-SA-4\.0/ })).toBeVisible();
    await expect(page.getByTestId('dataset-wordnet')).toContainText('Open English WordNet');
    await expect(page.getByTestId('dataset-wordnet_princeton')).toContainText('Princeton WordNet 3.1');

    // the terms are the catalog's: nothing to type them in, no dataset of a name of one's own
    await expect(page.getByRole('button', { name: 'Edit terms' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'New dataset' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Activate' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Delete' })).toHaveCount(0);
  });

  test('the instruction says where to download the file and under which terms the data comes', async ({
    page,
  }) => {
    await page.goto('/en/managing/datasets');

    await page.getByTestId('dataset-wiktionary').getByRole('button', { name: 'How to install' }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toContainText('Install: English Wiktionary');
    await expect(dialog).toContainText('kaikki.org-dictionary-English.jsonl.gz');
    await expect(dialog.getByRole('link', { name: 'Direct download' })).toHaveAttribute(
      'href',
      'https://kaikki.org/dictionary/English/kaikki.org-dictionary-English.jsonl.gz',
    );
    await expect(dialog.getByTestId('share-alike')).toContainText('has to stay under the same license');
    await expect(dialog).toContainText('Wiktionary contributors');
    await expect(dialog).toContainText('Datasets are never mixed');
    await expect(dialog).toContainText('under its license, CC-BY-SA-4.0');

    // SQLite: the instruction can be read, the file cannot be attached
    await expect(dialog.getByTestId('install-unsupported')).toBeVisible();
    await expect(dialog.getByRole('button', { name: 'Start' })).toBeDisabled();
    await dialog.getByRole('button', { name: 'Close' }).last().click();
    await expect(dialog).toBeHidden();

    // WordNet takes a second, optional file under a license of its own
    await page.getByTestId('dataset-wordnet').getByRole('button', { name: 'How to install' }).click();
    await expect(page.getByRole('dialog')).toContainText('english-wordnet-2025.zip');
    await expect(page.getByRole('dialog')).toContainText('cmudict.dict');
    await expect(page.getByRole('dialog').getByRole('link', { name: 'BSD 2-Clause License' })).toBeVisible();
  });

  test('the API reports the terms of the project dataset', async ({ request }) => {
    const meta = (await (await request.get(`${API_URL}/v1/meta`)).json()) as {
      data: { notice: string; dataset: string; source: string; license: string };
    };
    expect(meta.data).toEqual(
      expect.objectContaining({ dataset: 'default', source: 'vocab-bloom-hub', license: 'CC-BY-4.0' }),
    );
    expect(meta.data.notice).toContain('Generated by language models');
  });

  test('the import page offers no target while one dataset is installed', async ({ page }) => {
    await page.goto('/en/managing/import-dictionary');

    await expect(page.getByRole('button', { name: 'Start importing' })).toBeVisible();
    await expect(page.getByText('Import into')).toHaveCount(0);
  });
});
