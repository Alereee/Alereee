import React from 'react';
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { App } from 'antd';
import { DATASET_CATALOG } from 'server/core/constants/dataset_catalog';
import { EnDictionaryImportPhasesE } from 'server/src/modules/EnModule/modules/EnImportDictionary/constants';
import { DatasetT, DatasetsListT, ImportDictionaryChunkT } from 'server/types';

jest.mock('next-intl', () => ({
  useTranslations: () => (key: string, values?: Record<string, unknown>) =>
    values ? `${key} ${JSON.stringify(values)}` : key,
  useLocale: () => 'en',
}));

jest.mock('@/core/api/EnApi', () => ({
  EnApi: {
    getDatasets: jest.fn(),
    getDatasetUpdates: jest.fn(),
    installDataset: jest.fn(),
    activateDataset: jest.fn(),
    deleteDataset: jest.fn(),
  },
}));

import { EnApi } from '@/core/api/EnApi';
import { DatasetsSection } from '../index';

// what the API says about the datasets of the catalog: the default one installed and active
const listOf = (over: Record<string, Partial<DatasetT>> = {}, supported = true): DatasetsListT => {
  const datasets = DATASET_CATALOG.map((entry) => ({
    name: entry.name,
    title: entry.title,
    installed: entry.name === 'default',
    source: entry.source,
    language: entry.language,
    version: null,
    license: entry.license.spdx,
    license_url: entry.license.url,
    attribution: entry.attribution,
    attribution_url: entry.attribution_url,
    notice: entry.notice || null,
    active: entry.name === 'default',
    is_default: entry.name === 'default',
    created_at: entry.name === 'default' ? '2026-09-27T10:00:00.000Z' : null,
    imported_at: null,
    ...over[entry.name],
  }));
  return { supported, active: datasets.find((dataset) => dataset.active)?.name ?? 'default', datasets };
};

const INSTALLED = { installed: true, version: '2026.09.27', imported_at: '2026-09-27T10:05:00.000Z' };

const renderSection = (list: DatasetsListT) =>
  render(
    <App>
      <DatasetsSection initial={list} />
    </App>,
  );

const cardOf = (name: string) => within(screen.getByTestId(`dataset-${name}`));

const attach = (field: string, name: string): File => {
  const file = new File(['x'], name);
  const input = screen.getByTestId(`source-${field}`).querySelector('input[type="file"]') as HTMLInputElement;
  fireEvent.change(input, { target: { files: [file] } });
  return file;
};

type HandleChunkT = (chunk: ImportDictionaryChunkT) => void;

const mockInstall = (chunks: ImportDictionaryChunkT[], result: unknown = { success: true }) => {
  (EnApi.installDataset as jest.Mock).mockImplementation(
    async (_name: string, _files: unknown, handleChunk: HandleChunkT) => {
      chunks.forEach(handleChunk);
      return result;
    },
  );
};

// The datasets page of the admin UI (issue #527): the catalog, and the
// instruction that installs a dataset from the file of its source
describe('DatasetsSection', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    (EnApi.getDatasets as jest.Mock).mockResolvedValue(listOf());
    (EnApi.getDatasetUpdates as jest.Mock).mockResolvedValue({ enabled: true, datasets: [] });
  });

  it('shows every dataset of the catalog with its terms, installed or not', () => {
    renderSection(listOf());

    expect(DATASET_CATALOG.map((entry) => screen.getByTestId(`dataset-${entry.name}`))).toHaveLength(4);
    const own = cardOf('default');
    expect(own.getByText('status_active')).toBeInTheDocument();
    expect(own.getByText('about_default')).toBeInTheDocument();
    expect(own.getByRole('link', { name: /CC-BY-4\.0/ })).toHaveAttribute(
      'href',
      'https://creativecommons.org/licenses/by/4.0/',
    );
    // only the data of the project carries a notice for its readers
    expect(own.getByText(/Generated by language models/)).toBeInTheDocument();

    const wiktionary = cardOf('wiktionary');
    expect(wiktionary.getByText('English Wiktionary')).toBeInTheDocument();
    expect(wiktionary.getByText('status_not_installed')).toBeInTheDocument();
    expect(wiktionary.getByText('share_alike')).toBeInTheDocument();
    expect(wiktionary.getByRole('link', { name: /CC-BY-SA-4\.0/ })).toHaveAttribute(
      'href',
      'https://creativecommons.org/licenses/by-sa/4.0/',
    );
    expect(wiktionary.getByText(/Wiktionary contributors/)).toBeInTheDocument();
    expect(wiktionary.getByText('feature_translations')).toBeInTheDocument();
    expect(wiktionary.queryByText('feature_levels')).not.toBeInTheDocument();
    expect(wiktionary.getByText(/^size /)).toHaveTextContent('"entries":"787,000"');
    expect(wiktionary.getByText(/^size /)).toHaveTextContent('"size":"1.4 GB"');
    expect(cardOf('wordnet').queryByText('share_alike')).not.toBeInTheDocument();
  });

  it('has nothing to type the terms in and no way to make a dataset of a name', () => {
    renderSection(listOf({ wiktionary: INSTALLED }));

    expect(screen.queryByRole('textbox')).not.toBeInTheDocument();
    expect(screen.queryByText('edit_terms')).not.toBeInTheDocument();
    expect(screen.queryByText('create_title')).not.toBeInTheDocument();
  });

  it('offers the instruction for a dataset that is not installed, the import page for the one of the project', () => {
    renderSection(listOf());

    expect(cardOf('wiktionary').getByRole('button', { name: 'how_to_install' })).toBeInTheDocument();
    expect(cardOf('wiktionary').queryByRole('button', { name: 'activate' })).not.toBeInTheDocument();
    expect(cardOf('wiktionary').queryByRole('button', { name: 'delete' })).not.toBeInTheDocument();
    expect(cardOf('default').getByText('open_import').closest('a')).toHaveAttribute(
      'href',
      '/en/managing/import-dictionary',
    );
    expect(cardOf('default').queryByRole('button', { name: 'how_to_install' })).not.toBeInTheDocument();
  });

  it('says where to download the file, under which terms the data comes and what to know', () => {
    renderSection(listOf());
    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'how_to_install' }));

    const dialog = within(screen.getByRole('dialog'));
    expect(dialog.getByText(/^install_title /)).toHaveTextContent('English Wiktionary');
    expect(dialog.getByText('kaikki.org-dictionary-English.jsonl.gz')).toBeInTheDocument();
    expect(dialog.getByRole('link', { name: 'link_direct' })).toHaveAttribute(
      'href',
      'https://kaikki.org/dictionary/English/kaikki.org-dictionary-English.jsonl.gz',
    );
    expect(dialog.getByRole('link', { name: 'link_page' })).toHaveAttribute(
      'href',
      'https://kaikki.org/dictionary/English/',
    );
    expect(dialog.getByRole('link', { name: /CC-BY-SA-4\.0/ })).toHaveAttribute(
      'href',
      'https://creativecommons.org/licenses/by-sa/4.0/',
    );
    expect(dialog.getByText(/Wiktionary contributors/)).toBeInTheDocument();
    expect(dialog.getByTestId('share-alike')).toHaveTextContent('terms_share_alike');
    for (const key of ['step_attach', 'step_activate', 'warn_not_mixed', 'warn_content', 'warn_proxy']) {
      expect(dialog.getByText(key)).toBeInTheDocument();
    }
    expect(dialog.getByText(/^warn_edits /)).toHaveTextContent('CC-BY-SA-4.0');
    expect(dialog.getByText(/^warn_disk /)).toHaveTextContent('1.4 GB');
    // a first installation replaces nothing
    expect(dialog.queryByText('warn_update')).not.toBeInTheDocument();
    // nothing to start with before the file is attached
    expect(dialog.getByRole('button', { name: 'start' })).toBeDisabled();
  });

  it('names the second file of WordNet as optional, under a license of its own', () => {
    renderSection(listOf());
    fireEvent.click(cardOf('wordnet').getByRole('button', { name: 'how_to_install' }));

    const dialog = within(screen.getByRole('dialog'));
    expect(dialog.getByText('english-wordnet-2025.zip')).toBeInTheDocument();
    expect(dialog.getByText('step_optional_pronunciations')).toBeInTheDocument();
    expect(dialog.getByText('cmudict.dict')).toBeInTheDocument();
    expect(dialog.getByRole('link', { name: 'BSD 2-Clause License' })).toBeInTheDocument();
    expect(dialog.queryByTestId('share-alike')).not.toBeInTheDocument();
    expect(dialog.getByTestId('source-pronunciations')).toHaveTextContent('optional');
    // the notices the sources want on every copy can be read before anything is installed
    fireEvent.click(dialog.getByText('terms_full_text'));
    const notices = dialog.getAllByTestId('license-notice');
    expect(notices).toHaveLength(2);
    expect(notices[0]).toHaveTextContent('Open English Wordnet 2023 Copyright 2023');
    expect(notices[1]).toHaveTextContent('Carnegie Mellon University');

    // the required file is enough to start
    attach('file', 'english-wordnet-2025.zip');
    expect(dialog.getByRole('button', { name: 'start' })).toBeEnabled();
  });

  it('installs from the attached files and follows the conversion and the import', async () => {
    mockInstall([
      { percent: 0, stage: EnDictionaryImportPhasesE.converting_source },
      { percent: 100, stage: EnDictionaryImportPhasesE.converting_source },
      { percent: 40, stage: EnDictionaryImportPhasesE.saving_words },
      { percent: 100, stage: EnDictionaryImportPhasesE.completed, datasetVersion: '2026.09.27' },
    ]);
    (EnApi.getDatasets as jest.Mock).mockResolvedValue(listOf({ wordnet: INSTALLED }));
    renderSection(listOf());
    fireEvent.click(cardOf('wordnet').getByRole('button', { name: 'how_to_install' }));

    const release = attach('file', 'english-wordnet-2025.zip');
    const pronunciations = attach('pronunciations', 'cmudict.dict');
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'start' }));

    const done = await screen.findByTestId('install-done');
    expect(EnApi.installDataset).toHaveBeenCalledWith(
      'wordnet',
      { file: release, pronunciations },
      expect.any(Function),
      expect.any(Function),
    );
    // the card behind the dialog knows the dataset is there now
    await waitFor(() => expect(cardOf('wordnet').getByText('status_installed')).toBeInTheDocument());
    expect(cardOf('wordnet').getByText('2026.09.27')).toBeInTheDocument();
    expect(cardOf('wordnet').getByRole('button', { name: 'activate' })).toBeInTheDocument();
    // …and the dialog still reports the installation it was opened for
    expect(done).toHaveTextContent(/^done$/);
    expect(within(screen.getByRole('dialog')).getByText(/^install_title /)).toBeInTheDocument();
  });

  // a click outside the dialog closes it, like its cross and Escape; an installation that runs is not left that way
  describe('a click outside the instruction', () => {
    const clickOutside = () => {
      const outside = document.querySelector('.ant-modal-wrap') as HTMLElement;
      fireEvent.mouseDown(outside);
      fireEvent.mouseUp(outside);
      fireEvent.click(outside);
    };

    it('closes the dialog', async () => {
      renderSection(listOf());
      fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'how_to_install' }));
      expect(screen.getByRole('dialog')).toBeInTheDocument();

      clickOutside();

      await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
    });

    it('does not close it while the installation runs', async () => {
      let finish: (result: unknown) => void = () => undefined;
      (EnApi.installDataset as jest.Mock).mockImplementation(
        () =>
          new Promise((resolve) => {
            finish = resolve;
          }),
      );
      renderSection(listOf());
      fireEvent.click(cardOf('wordnet').getByRole('button', { name: 'how_to_install' }));
      attach('file', 'english-wordnet-2025.zip');
      fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'start' }));
      await waitFor(() => expect(EnApi.installDataset).toHaveBeenCalled());

      clickOutside();
      expect(screen.getByRole('dialog')).toBeInTheDocument();

      // once it is over the dialog closes like before
      finish({ success: true });
      await waitFor(() =>
        expect(within(screen.getByRole('dialog')).getByRole('button', { name: 'close' })).toBeEnabled(),
      );
      clickOutside();
      await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
    });
  });

  it('says what the server refused, and lets the admin try again', async () => {
    mockInstall([], { error: true, message: 'dataset_source_invalid', statusCode: 400 });
    renderSection(listOf());
    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'how_to_install' }));
    attach('file', 'something-else.zip');
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'start' }));

    expect(await screen.findByTestId('install-error')).toHaveTextContent('dataset_source_invalid');
    expect(within(screen.getByRole('dialog')).getByRole('button', { name: 'retry' })).toBeEnabled();

    // a file the server does not take for its size, and an answer it has no code for
    mockInstall([], { error: true, message: 'File too large', statusCode: 413 });
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'retry' }));
    await waitFor(() => expect(screen.getByTestId('install-error')).toHaveTextContent('too_large'));

    mockInstall([], { error: true, message: 'Bad Gateway', statusCode: 502 });
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'retry' }));
    await waitFor(() => expect(screen.getByTestId('install-error')).toHaveTextContent('unknown_error'));
  });

  it('takes a stream that ends before the last chunk for an installation that broke', async () => {
    mockInstall([{ percent: 30, stage: EnDictionaryImportPhasesE.converting_source }]);
    renderSection(listOf());
    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'how_to_install' }));
    attach('file', 'kaikki.org-dictionary-English.jsonl.gz');
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'start' }));

    expect(await screen.findByTestId('install-error')).toHaveTextContent('unknown_error');
    expect(screen.queryByTestId('install-done')).not.toBeInTheDocument();
  });

  it('updates an installed dataset from a newer file and reports what was replaced', async () => {
    mockInstall([
      {
        percent: 100,
        stage: EnDictionaryImportPhasesE.completed,
        updated_entries: 120,
        added_entries: 7,
        kept_user_modified: 3,
      },
    ]);
    (EnApi.getDatasets as jest.Mock).mockResolvedValue(listOf({ wiktionary: INSTALLED }));
    renderSection(listOf({ wiktionary: INSTALLED }));
    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'update' }));

    const dialog = within(screen.getByRole('dialog'));
    expect(dialog.getByText(/^update_title /)).toBeInTheDocument();
    expect(dialog.getByText('warn_update')).toBeInTheDocument();
    attach('file', 'kaikki.org-dictionary-English.jsonl.gz');
    fireEvent.click(dialog.getByRole('button', { name: 'start_update' }));

    const done = await screen.findByTestId('install-done');
    expect(done).toHaveTextContent('done_update');
    expect(done).toHaveTextContent('"updated":120');
    expect(done).toHaveTextContent('"kept":3');
  });

  it('activates an installed dataset and deletes one that is not active', async () => {
    (EnApi.activateDataset as jest.Mock).mockResolvedValue({ name: 'wiktionary' });
    (EnApi.deleteDataset as jest.Mock).mockResolvedValue({ success: true });
    (EnApi.getDatasets as jest.Mock).mockResolvedValue(listOf({ wiktionary: INSTALLED }));
    renderSection(listOf({ wiktionary: INSTALLED }));

    // neither the active dataset nor the one of the project can be deleted
    expect(cardOf('default').queryByRole('button', { name: 'delete' })).not.toBeInTheDocument();
    expect(cardOf('default').queryByRole('button', { name: 'activate' })).not.toBeInTheDocument();

    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'activate' }));
    // the button of the card, then the one of the confirmation
    fireEvent.click((await screen.findAllByRole('button', { name: 'activate' })).at(-1) as HTMLElement);
    await waitFor(() => expect(EnApi.activateDataset).toHaveBeenCalledWith('wiktionary'));

    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'delete' }));
    const confirm = (await screen.findAllByRole('button', { name: 'delete' })).at(-1) as HTMLElement;
    fireEvent.click(confirm);
    await waitFor(() => expect(EnApi.deleteDataset).toHaveBeenCalledWith('wiktionary'));
    expect(EnApi.getDatasets).toHaveBeenCalled();
  });

  // issue #530: what the source of an installed dataset has now
  describe('a newer file of the source', () => {
    const checked_at = '2026-11-01T12:00:00.000Z';
    const installed = listOf({
      wiktionary: { ...INSTALLED, version: '2026.09.25' },
      wordnet: { ...INSTALLED, version: '2025' },
    });

    it('is told on the card of the dataset, with the page it is downloaded from', async () => {
      (EnApi.getDatasetUpdates as jest.Mock).mockResolvedValue({
        enabled: true,
        datasets: [
          {
            name: 'wiktionary',
            installed: '2026.09.25',
            latest: '2026.10.30',
            url: 'https://kaikki.org/dictionary/English/',
            comparable: true,
            update_available: true,
            checked_at,
          },
          {
            name: 'wordnet',
            installed: '2025',
            latest: '2025',
            url: null,
            comparable: true,
            update_available: false,
            checked_at,
          },
        ],
      });
      renderSection(installed);

      const notice = within(await screen.findByTestId('dataset-update-wiktionary'));
      expect(
        notice.getByText('update_available {"latest":"2026.10.30","installed":"2026.09.25"}'),
      ).toBeInTheDocument();
      expect(notice.getByText(/update_hint/)).toBeInTheDocument();
      expect(notice.getByRole('link', { name: 'update_open' })).toHaveAttribute(
        'href',
        'https://kaikki.org/dictionary/English/',
      );
      expect(screen.getByTestId('dataset-source-version-wiktionary')).toHaveTextContent('2026.10.30');

      // the edition that is installed is the latest: what the source has is shown, nothing is told
      expect(screen.getByTestId('dataset-source-version-wordnet')).toHaveTextContent('2025');
      expect(screen.queryByTestId('dataset-update-wordnet')).not.toBeInTheDocument();
      // the datasets nothing is asked about say nothing of a source
      for (const name of ['default', 'wordnet_princeton']) {
        expect(screen.queryByTestId(`dataset-source-version-${name}`)).not.toBeInTheDocument();
      }
    });

    it('says when the source could not be asked, and stays silent when the check is off or fails', async () => {
      (EnApi.getDatasetUpdates as jest.Mock).mockResolvedValue({
        enabled: true,
        datasets: [
          {
            name: 'wiktionary',
            installed: '2026.09.25',
            latest: null,
            url: null,
            comparable: true,
            update_available: false,
            checked_at,
          },
        ],
      });
      const { unmount } = renderSection(installed);
      expect(await screen.findByTestId('dataset-source-version-wiktionary')).toHaveTextContent(
        'source_unknown',
      );
      expect(screen.queryByTestId('dataset-update-wiktionary')).not.toBeInTheDocument();
      unmount();

      for (const answer of [
        { enabled: false, datasets: [] },
        { error: true, message: 'unknown_error' },
      ]) {
        (EnApi.getDatasetUpdates as jest.Mock).mockResolvedValue(answer);
        const view = renderSection(installed);
        await waitFor(() => expect(EnApi.getDatasetUpdates).toHaveBeenCalled());
        expect(screen.queryByTestId('dataset-source-version-wiktionary')).not.toBeInTheDocument();
        expect(screen.queryByText(/unknown_error/)).not.toBeInTheDocument();
        view.unmount();
      }
    });

    it('says of a dataset recorded by the day of its installation that its edition is not known', async () => {
      (EnApi.getDatasetUpdates as jest.Mock).mockResolvedValue({
        enabled: true,
        datasets: [
          {
            name: 'wordnet',
            installed: '2026.09.27',
            latest: '2025',
            url: null,
            comparable: false,
            update_available: false,
            checked_at,
          },
        ],
      });
      renderSection(listOf({ wordnet: INSTALLED }));

      expect(await screen.findByTestId('dataset-version-unknown-wordnet')).toHaveTextContent('version_unknown');
      expect(screen.queryByTestId('dataset-update-wordnet')).not.toBeInTheDocument();
    });

    it('is not told of a dataset the instance does not hold', async () => {
      (EnApi.getDatasetUpdates as jest.Mock).mockResolvedValue({
        enabled: true,
        datasets: [
          {
            name: 'wiktionary',
            installed: null,
            latest: '2026.10.30',
            url: null,
            comparable: true,
            update_available: true,
            checked_at,
          },
        ],
      });
      renderSection(listOf());
      await waitFor(() => expect(EnApi.getDatasetUpdates).toHaveBeenCalled());
      expect(screen.queryByTestId('dataset-update-wiktionary')).not.toBeInTheDocument();
    });
  });

  it('shows the catalog on SQLite, says why nothing can be installed and offers no upload', () => {
    renderSection(listOf({}, false));

    expect(screen.getByTestId('datasets-unsupported')).toHaveTextContent('not_supported');
    expect(screen.getAllByTestId(/^dataset-/)).toHaveLength(4);
    expect(screen.queryByRole('button', { name: 'activate' })).not.toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'delete' })).not.toBeInTheDocument();

    // the instruction can be read; the files cannot be attached
    fireEvent.click(cardOf('wiktionary').getByRole('button', { name: 'how_to_install' }));
    const dialog = within(screen.getByRole('dialog'));
    expect(dialog.getByTestId('install-unsupported')).toBeInTheDocument();
    expect(dialog.getByRole('link', { name: 'link_direct' })).toBeInTheDocument();
    expect(dialog.getByRole('button', { name: /choose_file/ })).toBeDisabled();
    expect(dialog.getByRole('button', { name: 'start' })).toBeDisabled();
  });

  it('loads the list by itself when the page could not', async () => {
    (EnApi.getDatasets as jest.Mock).mockResolvedValue(listOf({ wordnet: INSTALLED }));
    render(
      <App>
        <DatasetsSection />
      </App>,
    );

    await waitFor(() => expect(cardOf('wordnet').getByText('status_installed')).toBeInTheDocument());
  });
});
